/**
 * Generates COMPONENTS.md — the single reference for authoring data pages: every
 * REGISTERED component with its props (kind, enum, required) and slots, plus which
 * `_helpers.cjs` helper covers it. Generated from the .component.yml schemas so it
 * never drifts. Run: `npm run manifest`.
 *
 * Also runs the ICON DRIFT CHECK: every icon-name enum in a component schema
 * must be a subset of the theme's curated set (scripts/copy-icons.mjs →
 * dist/icons). A component offering an icon that isn't shipped renders an
 * empty span — warn loudly.
 */
const fs = require('fs');
const path = require('path');
const { readSchemas } = require('./_schema.cjs');
const { themeRoot } = require('../lib/theme-paths.cjs');

const schemas = readSchemas();

// Which helper (from _helpers.cjs) authors a given component, for quick reference.
const HELPER_FOR = {
  section_hero: 'hero()',
  page_hero: 'pageHero()',
  section_stats: 'statBand()',
  stat: 'stat()',
  section_cards: 'cardGrid()',
  card: 'card()',
  card_news: 'newsCard()',
  card_event: 'eventCard()',
  section_split: 'split()',
  section_cta: 'cta()',
  section_richtext: 'richtext()',
  section_quote: 'quote()',
  section_gallery: 'gallery()',
  accordion: 'accordion()',
  accordion_item: 'accordionItem()',
  alert_banner: 'alert()',
  document_list: 'docList()',
  document_item: 'docItem()',
  button: 'button()',
  heading: 'heading()',
  icon: 'icon()',
  image: 'image()',
  divider: 'divider()',
  spacer: 'spacer()',
};

const KIND_NOTE = {
  image: 'image — pass `img(src, alt)`',
  link: 'link — plain string (e.g. `/about`)',
  richtext: 'rich-text — plain HTML string (use `rt()`)',
  boolean: 'boolean',
};

function propLine(pn, p) {
  const bits = [];
  bits.push('`' + pn + '`' + (p.required ? ' **(required)**' : ''));
  if (p.enum) {
    const list = p.enum.length > 8
      ? p.enum.slice(0, 8).map((v) => '`' + v + '`').join(' / ') + ` / … (${p.enum.length} values)`
      : p.enum.map((v) => '`' + v + '`').join(' / ');
    bits.push('enum: ' + list);
  } else {
    bits.push(KIND_NOTE[p.kind] || p.kind);
  }
  return '  - ' + bits.join(' — ');
}

// ── Icon drift check ────────────────────────────────────────────────────
const iconsDir = path.join(themeRoot, 'dist', 'icons');
const shipped = new Set(
  fs.existsSync(iconsDir)
    ? fs.readdirSync(iconsDir).filter((f) => f.endsWith('.svg')).map((f) => f.replace(/\.svg$/, ''))
    : [],
);
shipped.add('none');
let drift = 0;
for (const c of Object.values(schemas)) {
  for (const [pn, p] of Object.entries(c.props)) {
    if (!p.enum || !p.enum.includes('none')) continue;
    // Heuristic: icon enums always include 'none' and mostly shipped names.
    const iconish = p.enum.filter((v) => shipped.has(v)).length > p.enum.length / 2;
    if (!iconish) continue;
    for (const v of p.enum) {
      if (!shipped.has(v)) {
        console.warn(`⚠ icon drift: ${c.name}.${pn} offers "${v}" but dist/icons has no ${v}.svg (add it to scripts/copy-icons.mjs and rebuild)`);
        drift++;
      }
    }
  }
}
if (!drift) console.log('icon drift check: OK (all icon enums ⊆ curated set)');

const registered = Object.values(schemas)
  .filter((c) => c.registered)
  .sort((a, b) => a.name.localeCompare(b.name));

let md = `<!-- GENERATED by frontend/site/gen-manifest.cjs — do not edit by hand. Run \`npm run manifest\`. -->

# DrupalX Canvas — component reference

The **registered** components (have a \`canvas.component.sdc.drupalx_theme.*\` config →
**available in the Canvas editor**). Author pages as data (\`pages-data/*.cjs\`) using these.
Prefer the helper where one exists; otherwise write \`{ component, props, slots }\` directly.

**Prop forms** (the bridge wraps them for Canvas; in data keep them PLAIN):
- image → \`img(src, alt)\` object · link/url → plain string · rich-text → plain HTML string (\`rt()\`).
- enum props must use one of the listed values — never \`''\`, use \`'none'\` (\`npm run validate\` checks this).

Helpers in \`pages-data/_helpers.cjs\`: \`hero, pageHero, statBand, stat, cardGrid, card,
newsCard, eventCard, split, cta, richtext, quote, gallery, accordion, accordionItem,
alert, docList, docItem, button, heading, icon, image, divider, spacer, img, rt\`.

---

`;

for (const c of registered) {
  md += `### \`${c.name}\``;
  if (HELPER_FOR[c.name]) md += `  · helper: \`${HELPER_FOR[c.name]}\``;
  md += '\n\n';
  const propEntries = Object.entries(c.props);
  if (propEntries.length) {
    md += 'Props:\n';
    for (const [pn, p] of propEntries) md += propLine(pn, p) + '\n';
  } else {
    md += '_No props._\n';
  }
  if (c.slots.length) {
    md += `\nSlots: ${c.slots.map((s) => '`' + s + '`').join(', ')} (each holds an array of child nodes)\n`;
  }
  md += '\n';
}

const { componentsMd: OUT } = require('../lib/theme-paths.cjs');
fs.writeFileSync(OUT, md);
console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${registered.length} registered components).`);
